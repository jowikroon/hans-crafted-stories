import { applyMaskTokens, type MaskingConfig } from "@/lib/masking";

export type ArticleMaskContext = {
  cfg: MaskingConfig | null | undefined;
  counters: Record<string, number>;
};

/** Escape text and quoted HTML attributes before inserting CMS content into HTML. */
export const escapeArticleHtml = (value: string) => value
  .replace(/&/g, "&amp;")
  .replace(/</g, "&lt;")
  .replace(/>/g, "&gt;")
  .replace(/"/g, "&quot;")
  .replace(/'/g, "&#39;");

const SAFE_HREF_RE = /^(https?:\/\/|\/(?![/\\])|#|mailto:)/i;
const unsafeUrlCharacter = (char: string) => {
  const code = char.charCodeAt(0);
  return code <= 32 || code === 127 || '<>"\''.includes(char);
};

function normalizeArticleHref(rawHref: string): string | null {
  const href = rawHref.trim();
  if (!href || Array.from(href).some(unsafeUrlCharacter) || !SAFE_HREF_RE.test(href)) return null;
  if (href === "/blog" || href === "/blog/") return "/writing";
  if (href.startsWith("/blog/")) return `/writing/${href.slice(6)}`;
  return href;
}

function renderAnchor(rawHref: string, label: string): string | null {
  const href = normalizeArticleHref(rawHref);
  if (!href) return null;
  const external = /^https?:\/\//i.test(href);
  return `<a href="${href.replace(/"/g, "&quot;")}"${external ? ' target="_blank" rel="noopener noreferrer"' : ""}>${label}</a>`;
}

/**
 * Small, intentionally restricted inline Markdown renderer for CMS articles.
 * Only supported formatting is generated; author-supplied HTML never executes.
 * Code, links and escaped punctuation are shielded while other syntax is parsed.
 */
export function renderArticleInline(source: string, mask?: ArticleMaskContext): string {
  // Historical CMS article contains a stray escaped opening '*' before a long
  // paragraph. A lone marker is a copy/paste artefact, not intended emphasis.
  const withoutBold = source.replace(/\*\*[^*]+\*\*/g, "");
  const normalized = /^\\\*\S/.test(source) && !/\*(?!\*)/.test(withoutBold.slice(2))
    ? source.slice(2)
    : source;

  let out = escapeArticleHtml(normalized.replace(/[\uE000\uE001]/g, "�"));
  if (mask) out = applyMaskTokens(out, mask.cfg, mask.counters);

  const stored: string[] = [];
  const shield = (html: string) => {
    const index = stored.push(html) - 1;
    return `\uE000${index}\uE001`;
  };

  // Mask-token HTML is generated by our own masking helper. Keep it intact.
  out = out.replace(/<span class="mask-token"[\s\S]*?<\/span>/g, (html) => shield(html));
  out = out.replace(/\\(.)/g, (whole, literal: string) =>
    "\\`*_{}[]()#+.!~-".includes(literal) ? shield(literal) : whole);
  out = out.replace(/`([^`\n]+)`/g, (_match, code: string) => shield(`<code>${code}</code>`));
  out = out.replace(/\[([^\]\n]+)\]\(([^)\s]+)(?:\s+&quot;[^&]*&quot;)?\)/g,
    (whole, label: string, href: string) => shield(renderAnchor(href, label) ?? whole));

  out = out
    .replace(/\*\*\*([^*\n]+)\*\*\*/g, "<strong><em>$1</em></strong>")
    .replace(/\*\*([^*\n]+)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[^*])\*([^*\n]+)\*(?!\*)/g, "$1<em>$2</em>")
    .replace(/(^|[^_])_([^_\n]+)_(?!_)/g, "$1<em>$2</em>")
    .replace(/~~([^~\n]+)~~/g, "<s>$1</s>");

  const urlRegex = /(^|[\s(])((?:https?:\/\/|www\.)[^\s<>"')]*[^\s<>"').,;:!?])/g;
  out = out.split(/(<[^>]+>)/g).map((segment) =>
    segment.startsWith("<") ? segment : segment.replace(urlRegex, (_match, before: string, url: string) => {
      const href = /^www\./i.test(url) ? `https://${url}` : url;
      return `${before}${shield(renderAnchor(href, url) ?? url)}`;
    })
  ).join("");

  return out.replace(/\uE000(\d+)\uE001/g, (_match, index: string) => stored[Number(index)] ?? "");
}

/** Markdown image URLs become HTML attributes; don't allow SVG/data/script URLs. */
export function safeArticleImageSource(raw: string): string | null {
  if (!/^https?:\/\//i.test(raw) || Array.from(raw).some((c) => unsafeUrlCharacter(c) || c === "\\")) return null;
  try {
    const url = new URL(raw);
    return (url.protocol === "https:" || url.protocol === "http:") && url.hostname ? raw : null;
  } catch {
    return null;
  }
}
